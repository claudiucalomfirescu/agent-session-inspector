#!/usr/bin/env python3
"""Build viz/dealership/personas.json from company/personas/*.md and company/avatars/*.svg.

The persona Markdown files (YAML frontmatter + Markdown body) are the source of
truth. This script flattens them into one small JSON document the 3D scene can
read, embeds each SVG avatar as a data URI, and inlines the same JSON into
index.html so the page works when opened straight from disk or published as a
single-file artifact.

If no persona files exist yet, a placeholder roster is written instead so the
scene still renders.

Usage:  python3 viz/dealership/build_personas.py
"""
from __future__ import annotations

import base64
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PERSONA_DIR = ROOT / "company" / "personas"
AVATAR_DIR = ROOT / "company" / "avatars"
OUT_JSON = HERE / "personas.json"
INDEX_HTML = HERE / "index.html"

# Used only until company/personas/*.md exists.
PLACEHOLDERS = [
    ("victor-hale", "Victor Hale", "General Manager", "Management", "gm-office", None),
    ("maria-santos", "Maria Santos", "Receptionist & Office Coordinator", "Admin", "reception", "victor-hale"),
    ("priya-nair", "Priya Nair", "Finance & Admin Officer", "Admin", "back-office", "victor-hale"),
    ("daniel-reed", "Daniel Reed", "Sales Manager", "Sales", "sales-office", "victor-hale"),
    ("sofia-marin", "Sofia Marin", "Sales Consultant", "Sales", "showroom", "daniel-reed"),
    ("tom-becker", "Tom Becker", "Sales Consultant", "Sales", "showroom", "daniel-reed"),
    ("elena-popescu", "Elena Popescu", "Aftersales (Service) Manager", "Service", "service-desk", "victor-hale"),
    ("james-okafor", "James Okafor", "Service Advisor", "Service", "service-desk", "elena-popescu"),
    ("nina-kovac", "Nina Kovac", "Service Advisor", "Service", "service-desk", "elena-popescu"),
    ("lucas-meyer", "Lucas Meyer", "Master Technician", "Workshop", "workshop", "elena-popescu"),
    ("aisha-rahman", "Aisha Rahman", "EV & Electrical Technician", "Workshop", "workshop", "elena-popescu"),
    ("mark-doyle", "Mark Doyle", "Parts & Supply Chain Coordinator", "Parts", "parts-counter", "elena-popescu"),
]

FRONTMATTER = re.compile(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", re.S)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    m = FRONTMATTER.match(text)
    if not m:
        return {}, text
    try:
        import yaml  # type: ignore

        meta = yaml.safe_load(m.group(1)) or {}
    except ImportError:
        meta = {}
        for line in m.group(1).splitlines():
            if ":" in line and not line.startswith((" ", "-")):
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip().strip("'\"")
    return meta, m.group(2).strip()


def jsonable(value):
    """YAML can produce dates and other objects; make everything JSON-safe."""
    if isinstance(value, dict):
        return {str(k): jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [jsonable(v) for v in value]
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    return str(value)


def avatar_uri(pid: str) -> str | None:
    path = AVATAR_DIR / f"{pid}.svg"
    if not path.exists():
        return None
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:image/svg+xml;base64,{data}"


def load_personas() -> tuple[list[dict], str]:
    files = sorted(PERSONA_DIR.glob("*.md")) if PERSONA_DIR.exists() else []
    people = []
    for f in files:
        if f.name.lower() in {"readme.md", "index.md"}:
            continue
        meta, body = parse_frontmatter(f.read_text(encoding="utf-8"))
        if not meta.get("name"):
            continue
        meta = jsonable(meta)
        meta.setdefault("id", f.stem)
        meta["profile_md"] = body
        meta["avatar"] = avatar_uri(meta["id"])
        people.append(meta)
    if people:
        return people, "company/personas"
    placeholders = [
        {
            "id": pid,
            "name": name,
            "role": role,
            "department": dept,
            "workspace": ws,
            "reports_to": boss,
            "summary": "Placeholder profile. The full persona is generated by the company design thread.",
            "avatar": avatar_uri(pid),
        }
        for pid, name, role, dept, ws, boss in PLACEHOLDERS
    ]
    return placeholders, "placeholder"


def main() -> int:
    people, source = load_personas()
    doc = {"company": "VXC Motors", "source": source, "people": people}
    OUT_JSON.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    html = INDEX_HTML.read_text(encoding="utf-8")
    inline = json.dumps(doc, ensure_ascii=False).replace("</", "<\\/")
    new_html, n = re.subn(
        r'(<script type="application/json" id="personas-data">)(.*?)(</script>)',
        lambda m: m.group(1) + inline + m.group(3),
        html,
        count=1,
        flags=re.S,
    )
    if n != 1:
        print("personas-data block not found in index.html", file=sys.stderr)
        return 1
    INDEX_HTML.write_text(new_html, encoding="utf-8")
    print(f"{len(people)} people from {source} -> {OUT_JSON.relative_to(ROOT)} and index.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
