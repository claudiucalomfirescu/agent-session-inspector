"""Write TOOLS.md: every tool an agent can call, which application serves it, and what is behind it.

    python -m apps.catalogue            # rewrites TOOLS.md from the tool registry (tests check it is current)

Part of K-vxc-tools@1 (SPEC.md §3). Generated, so it cannot drift from the code.
"""
from pathlib import Path

from apps import tools  # noqa: F401  (registers the tools)
from apps.common import REGISTRY, ROOT, SYSTEM_DB
from apps.server import APP_NAMES

DEFAULT_PORTS = {"internal": 8100, "bmw_portal": 8200}  # documented defaults, not this process's env

BEHIND = {
    "crm": "Real service: Python functions over DuckDB tables `customers`, `leads`, `test_drives`, `activities` "
           "(data/vxc.duckdb). Deterministic, no LLM.",
    "dms": "Real service: DuckDB tables `vehicles`, `deals`, `approvals`, `order_requests`, `invoices`. Enforces the "
           "discount and stock-order approval rules (apps/rules.py). No LLM.",
    "workshop": "Real service: DuckDB tables `bookings`, `job_cards`, `job_lines`, `time_entries`; goodwill and "
                "warranty approvals go to `approvals`. No LLM.",
    "parts": "Real service: DuckDB tables `parts`, `parts_movements`, `parts_requests`. No LLM.",
    "finance": "Real service: DuckDB tables `invoices`, `ledger`; KPIs and commission computed by SQL. No LLM.",
    "mail": "Real mailbox: DuckDB table `messages`. mail_send stores a message; the recipient finds it with "
            "mail_inbox / mail_read. Outside parties (customers, BMW) have mailboxes here too (actor ext:<email>). "
            "No LLM inside; the director only learns *that* a message arrived (GET /events) and wakes the recipient.",
    "chat": "Real chat channel: DuckDB table `chat_messages`. chat_send stores, chat_unread delivers. No LLM inside; "
            "the director wakes the recipient, who reads the text by tool call.",
    "bmw_portal": "External system, separate service and database (data/bmw_portal.duckdb): catalogue, car and "
                  "parts orders (status advanced by the simulated clock), recalls, bulletins, warranty claims "
                  "(decided by a fixed rule after 3 days). **bmw_open_tech_case is a judgment tool**: BMW's "
                  "technical support agent (an LLM, user `bmw-tech-support`, through the proxy) writes the answer.",
}


def render():
    lines = ["# Tool catalogue · vxc-motors-sim", "",
             "> Generated by `python -m apps.catalogue` from the tool registry. Part of **K-vxc-tools@1** (SPEC.md §3).",
             "> Every tool is called by an agent over HTTP: `POST <service>/call {\"actor\", \"tool\", \"args\"}`.", ""]
    lines += ["## Applications", "", "| App id | Application | Service | Tools | What is really behind it |",
              "|---|---|---|---:|---|"]
    by_app = {}
    for t in REGISTRY.values():
        by_app.setdefault(t.system, []).append(t)
    for app, ts in by_app.items():
        svc = SYSTEM_DB[app]
        lines.append(f"| `{app}` | {APP_NAMES[app]} | `{svc}` :{DEFAULT_PORTS[svc]} | {len(ts)} | {BEHIND[app]} |")
    lines += ["", f"Total: **{len(REGISTRY)} tools**.", ""]
    for app, ts in by_app.items():
        lines += [f"## {APP_NAMES[app]} (`{app}`)", "", "| Tool | Writes | Parameters (required in bold) | Description |",
                  "|---|:-:|---|---|"]
        for t in ts:
            spec = t.spec()["function"]
            req = set(spec["parameters"]["required"])
            params = ", ".join(f"**{k}**" if k in req else k for k in spec["parameters"]["properties"]) or "–"
            desc = t.description.replace("|", "/")
            judge = " ⚖ judgment: answered by an agent" if t.prepare else ""
            lines.append(f"| `{t.name}` | {'✎' if t.writes else ''} | {params} | {desc}{judge} |")
        lines.append("")
    return "\n".join(lines)


def main():
    Path(ROOT / "TOOLS.md").write_text(render(), encoding="utf-8")
    print(f"TOOLS.md: {len(REGISTRY)} tools")


if __name__ == "__main__":
    main()
